/**
 * 账单问题信号闸门单测（08 修订案 A18 热修复五轮 + 复审修补）：案例路径
 * 的前置过滤。锁定两族语料：账单分析问法（时间窗/金额/类目/商户/账务
 * 实体）必须判定为账单问题（跳过案例检索直转在线兜底）；维权/攻略/政策
 * 问法必须保留案例路径。语料来自 A18 实测误答面（TF-IDF 对账单问法会
 * 越过 0.15 阈值）与攻略问法反例。
 * 复审修补补齐三类盲区：① 无花费词的账单词族（费用/开支/账单/多少）；
 * ② 月份短语 + 花费词 + 维权叙事的组合（旧闸门误判为账单问题）；
 * ③ 花费词被空格打断的变体（旧闸门静默放行）。
 */
import { describe, expect, it } from "vitest";

import { isBillQuestion } from "@/lib/assistant/bill-signal";

describe("账单问题信号闸门", () => {
  it("账单分析问法判定为账单问题（跳过案例路径）", () => {
    for (const question of [
      "上上上个月花费多少费用",
      "上上上个月花了多少钱",
      "上上上个月消费了多少",
      "前三个月外卖花了多少",
      "三个月前花了多少",
      "上两个月花了多少",
      "本月消费总额多少",
      "消费总额多少",
      "我花了多少钱",
      "账单里哪个类目花钱最多",
      "这个月外卖花了多少",
      "这个月开销大吗",
      "深夜消费多少",
      "有哪些订阅在扣费",
      "我的订阅有哪些",
      // 复审修补：无花费词的账单词族（旧闸门 SPEND 早退漏判，被案例抢答）
      "上上上个月费用是多少",
      "前两个月的费用是多少",
      "三个月前开支多少",
      "这个月账单多少",
      // 复审修补：计数问法在前（旧正则只认花费词在前、问额词在后）
      "有几笔不明扣费怎么办",
      // 复审修补：花费词被空格打断的变体（归一后应等价）
      "这个月花 了多少",
      "上个月花 费多少",
      "上上上个月 花费多少费用",
    ]) {
      expect(isBillQuestion(question), question).toBe(true);
    }
  });

  it("维权/攻略/政策问法保留案例路径", () => {
    for (const question of [
      "健身房年卡开业三个月就关门了怎么办",
      "双11 大促期间我该怎么规划消费",
      "网购被虚假宣传骗了怎么办",
      "外卖吃到异物怎么索赔",
      "怎么取消自动续费",
      "怎么追回预付卡余额",
      "被商家骗了怎么投诉",
      "快递丢了怎么索赔",
      "年货节什么时候开始",
      "健身卡办完花了一万块怎么办",
      // 复审修补：月份短语 + 花费词的维权叙事（旧闸门误判为账单问题，
      // 把本可零 API 命中的维权案例挡出案例路径）
      "三个月前健身房跑路，我花了三千办卡，怎么维权",
      "上个月被乱扣费怎么办",
      "上上个月被骗了三千块怎么办",
      "三个月前花了五千办健身卡现在关门了怎么办",
      "开业三个月花了四千就倒闭了能退钱吗",
      "两个月前花了八百办的健身卡跑路了怎么办",
      "三个月花了五千减肥没效果能退款吗",
    ]) {
      expect(isBillQuestion(question), question).toBe(false);
    }
  });
});
